"""Codeframe: the set of codes/themes for verbatim analysis.

A codeframe is auto-generated by LLM from sample verbatims, then applied to
code all open-ends in the study. Codes are hierarchical (parent/child) and
support multi-coding (one verbatim can have multiple codes).
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class CodeType(StrEnum):
    THEME = "theme"  # conceptual grouping (e.g. "Product Quality")
    SENTIMENT = "sentiment"  # positive/negative/neutral overlay
    ACTION = "action"  # caller should do something


@dataclass
class Code:
    """One code/theme."""

    id: str  # unique, e.g. "Q1_PROD_QUALITY"
    label: str  # "Product Quality Issues"
    description: str  # "Mentions defects, durability, performance"
    type: CodeType = CodeType.THEME
    parent_id: str | None = None  # hierarchical: child codes roll up
    examples: list[str] = None  # 2–3 example phrases that trigger this code

    def __post_init__(self) -> None:
        if self.examples is None:
            self.examples = []


@dataclass
class CodeFrame:
    """The complete set of codes for a study."""

    question_var: str  # which open-end variable (e.g. "q10_open")
    codes: list[Code]
    allow_multi: bool = True  # one verbatim can have multiple codes
    version: int = 1

    def __post_init__(self) -> None:
        self._by_id = {c.id: c for c in self.codes}

    def __getitem__(self, code_id: str) -> Code:
        return self._by_id[code_id]

    def by_parent(self, parent_id: str | None = None) -> list[Code]:
        """Codes at a specific level (root if parent_id=None)."""
        return [c for c in self.codes if c.parent_id == parent_id]

    def to_prompt_text(self) -> str:
        """Render the codeframe as a prompt snippet for the coder."""
        lines = [f"Question: {self.question_var}\nCodes:\n"]
        for c in self.codes:
            indent = "  " if c.parent_id else ""
            lines.append(f"{indent}{c.id}: {c.label}\n")
            lines.append(f"{indent}  Description: {c.description}\n")
            if c.examples:
                lines.append(f"{indent}  Examples: {' | '.join(c.examples)}\n")
        return "".join(lines)


CODEFRAME_GENERATION_SCHEMA = {
    "type": "object",
    "properties": {
        "codes": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "id": {"type": "string", "description": "Uppercase code ID"},
                    "label": {"type": "string"},
                    "description": {"type": "string"},
                    "examples": {"type": "array", "items": {"type": "string"}, "maxItems": 3},
                },
                "required": ["id", "label", "description", "examples"],
            },
            "minItems": 3,
            "maxItems": 20,
        }
    },
    "required": ["codes"],
}

